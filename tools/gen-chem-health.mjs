function build(list, category, startIndex, forceSourceFlagIndex) {
  return list.map(([question, choices, explanation, source, isVerified], i) => {
    const q = {
      id: `${category}-${String(startIndex + i).padStart(3, '0')}`,
      category, question, choices, correctIndex: 0, explanation,
      verified: forceSourceFlagIndex ? Boolean(isVerified) : true,
    };
    if (q.verified) q.source = source;
    return q;
  });
}

