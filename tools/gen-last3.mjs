function make(list, category, offset = 0) {
  return list.map(([question, choices, explanation, source, forced], i) => {
    const isV = source !== undefined ? (forced === undefined ? true : Boolean(forced)) : false;
    const q = {
      id: `${category}-${String(offset + i + 1).padStart(3, '0')}`,
      category, question, choices, correctIndex: 0, explanation, verified: isV,
    };
    if (isV) q.source = source;
    return q;
  });
}

